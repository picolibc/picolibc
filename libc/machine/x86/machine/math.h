#define __HAVE_HW_FLOAT 1
#endif
#if !defined(_SOFT_FLOAT) || defined(__SSE2_MATH__)
#define __HAVE_HW_DOUBLE 1
#endif
#ifndef _SOFT_FLOAT
#define __HAVE_HW_LONG_DOUBLE 1
#endif

#endif /* _MACHINE_MATH_H_ */
